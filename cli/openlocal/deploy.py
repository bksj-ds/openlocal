"""Secure Compose generation and lifecycle operations."""

from __future__ import annotations

import json
import os
import subprocess
import tempfile
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import yaml

OPEN_WEBUI_IMAGE = "ghcr.io/open-webui/open-webui:v0.11.4"


class DeploymentError(RuntimeError):
    """Deployment generation or lifecycle operation failed."""


def openlocal_home() -> Path:
    configured = os.environ.get("OPENLOCAL_HOME")
    return Path(configured).expanduser() if configured else Path.home() / ".openlocal"


def compose_path(home: Path | None = None) -> Path:
    return (home or openlocal_home()) / "compose.yaml"


def state_path(home: Path | None = None) -> Path:
    return (home or openlocal_home()) / "state.json"


def render_compose(profile: dict[str, Any], with_ui: bool = False) -> str:
    model = profile["model"]
    runtime = profile["runtime"]
    command: list[str] = [
        "--model",
        str(model["id"]),
        "--served-model-name",
        str(model["id"]),
        "--host",
        "0.0.0.0",
        "--port",
        "8000",
        "--max-model-len",
        str(runtime["max_model_len"]),
        "--gpu-memory-utilization",
        str(runtime["gpu_memory_utilization"]),
        "--max-num-seqs",
        str(runtime["max_num_seqs"]),
    ]
    if model["quantization"] != "none":
        command.extend(["--quantization", str(model["quantization"])])

    services: dict[str, Any] = {
        "vllm": {
            "image": profile["backend"]["image"],
            "restart": "unless-stopped",
            "ports": ["127.0.0.1:8000:8000"],
            "volumes": ["model-cache:/root/.cache/huggingface"],
            "environment": {"HF_HOME": "/root/.cache/huggingface"},
            "command": command,
            "ipc": "host",
            "healthcheck": {
                "test": [
                    "CMD",
                    "python",
                    "-c",
                    "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/health', timeout=5)",
                ],
                "interval": "10s",
                "timeout": "6s",
                "retries": 180,
                "start_period": "30s",
            },
            "deploy": {
                "resources": {
                    "reservations": {
                        "devices": [{"driver": "nvidia", "count": 1, "capabilities": ["gpu"]}]
                    }
                }
            },
        }
    }
    volumes: dict[str, Any] = {"model-cache": {"name": "openlocal-model-cache"}}
    if with_ui:
        services["open-webui"] = {
            "image": OPEN_WEBUI_IMAGE,
            "restart": "unless-stopped",
            "ports": ["127.0.0.1:3000:8080"],
            "environment": {
                "OPENAI_API_BASE_URL": "http://vllm:8000/v1",
                "WEBUI_AUTH": "true",
            },
            "volumes": ["open-webui-data:/app/backend/data"],
            "depends_on": {"vllm": {"condition": "service_healthy"}},
        }
        volumes["open-webui-data"] = {"name": "openlocal-webui-data"}

    document = {
        "name": "openlocal",
        "services": services,
        "volumes": volumes,
    }
    header = "# Generated by OpenLocal. Edit profiles, not this file.\n"
    return header + yaml.safe_dump(document, sort_keys=False, allow_unicode=True)


def write_atomic(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        temporary.replace(path)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def write_deployment(profile: dict[str, Any], with_ui: bool, home: Path | None = None) -> Path:
    selected_home = home or openlocal_home()
    generated = compose_path(selected_home)
    write_atomic(generated, render_compose(profile, with_ui))
    state = {
        "schema_version": "1.0",
        "profile_id": profile["id"],
        "model_id": profile["model"]["id"],
        "with_ui": with_ui,
        "compose_file": str(generated),
    }
    write_atomic(state_path(selected_home), json.dumps(state, indent=2, sort_keys=True) + "\n")
    return generated


def read_state(home: Path | None = None) -> dict[str, Any]:
    path = state_path(home)
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise DeploymentError("OpenLocal is not installed; run openlocal install first") from exc
    except (OSError, json.JSONDecodeError) as exc:
        raise DeploymentError(f"cannot read deployment state: {exc}") from exc
    if not isinstance(value, dict) or value.get("schema_version") != "1.0":
        raise DeploymentError("deployment state has an unsupported schema")
    return value


def compose_command(arguments: Sequence[str], home: Path | None = None) -> list[str]:
    path = compose_path(home)
    if not path.is_file():
        raise DeploymentError("generated Compose file is missing; run openlocal install")
    return ["docker", "compose", "-f", str(path), *arguments]


def run_compose(
    arguments: Sequence[str], home: Path | None = None, capture: bool = False
) -> subprocess.CompletedProcess[str]:
    command = compose_command(arguments, home)
    try:
        return subprocess.run(
            command,
            check=False,
            text=True,
            encoding="utf-8",
            errors="replace",
            capture_output=capture,
        )
    except (FileNotFoundError, PermissionError) as exc:
        raise DeploymentError(f"cannot run Docker Compose: {exc}") from exc


def select_profile(
    profiles: list[dict[str, Any]], recommendations: list[Any], profile_id: str | None
) -> dict[str, Any]:
    if profile_id:
        for profile in profiles:
            if profile["id"] == profile_id:
                return profile
        raise DeploymentError(f"unknown profile: {profile_id}")
    if not recommendations:
        raise DeploymentError("no compatible profile found for this hardware")
    for category in ("BALANCED", "FAST", "MAX QUALITY"):
        for item in recommendations:
            if item.category == category:
                return item.profile
    return recommendations[0].profile
